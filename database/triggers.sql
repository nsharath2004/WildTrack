USE wildlife_management;

DROP TRIGGER IF EXISTS after_animal_insert;
DROP TRIGGER IF EXISTS after_threat_insert;
DROP TRIGGER IF EXISTS before_animal_delete;

DELIMITER $$

-- -----------------------------------------------------------------------------
-- TRIGGER 1: after_animal_insert
-- Purpose: Automatically writes an entry into wildlife_audit_log whenever an
--          animal record is registered, capturing the event timestamp and ID.
-- -----------------------------------------------------------------------------
CREATE TRIGGER after_animal_insert
AFTER INSERT ON Animals
FOR EACH ROW
BEGIN
    INSERT INTO wildlife_audit_log (action_type, table_name, record_id, description)
    VALUES (
        'INSERT',
        'Animals',
        NEW.animal_id,
        CONCAT('New animal enrolled: "', NEW.animal_name, '" (Tag: ', NEW.tag_number, '), Species ID: ', NEW.species_id, ', Area ID: ', NEW.area_id)
    );
END$$

-- -----------------------------------------------------------------------------
-- TRIGGER 2: after_threat_insert
-- Purpose: Emergency incident automation. If a newly logged threat carries
--          'Critical' severity, an investigation row is automatically added to
--          the Incidents table, alerting rangers without human notification delay.
-- -----------------------------------------------------------------------------
CREATE TRIGGER after_threat_insert
AFTER INSERT ON Threats
FOR EACH ROW
BEGIN
    IF NEW.severity = 'Critical' THEN
        INSERT INTO Incidents (
            incident_title,
            animal_id,
            threat_id,
            incident_date,
            description,
            location,
            severity,
            status,
            resolved_date
        ) VALUES (
            CONCAT('AUTOGENERATED EMERGENCY: Critical Threat - ', NEW.threat_type),
            NULL,
            NEW.threat_id,
            NEW.threat_date,
            CONCAT('Emergency incident automatically dispatched by database trigger upon logging Critical Threat: ', NEW.description),
            NEW.location,
            'Critical',
            'Open',
            NULL
        );
    END IF;
END$$

-- -----------------------------------------------------------------------------
-- TRIGGER 3: before_animal_delete
-- Purpose: Historical record preservation. Before an animal is deleted, its
--          entire historical profile is archived in deleted_animals_log.
-- -----------------------------------------------------------------------------
CREATE TRIGGER before_animal_delete
BEFORE DELETE ON Animals
FOR EACH ROW
BEGIN
    INSERT INTO deleted_animals_log (
        original_animal_id,
        animal_name,
        species_id,
        age,
        gender,
        health_status,
        area_id,
        tag_number,
        notes,
        original_created_at
    ) VALUES (
        OLD.animal_id,
        OLD.animal_name,
        OLD.species_id,
        OLD.age,
        OLD.gender,
        OLD.health_status,
        OLD.area_id,
        OLD.tag_number,
        OLD.notes,
        OLD.created_at
    );
END$$

DELIMITER ;
